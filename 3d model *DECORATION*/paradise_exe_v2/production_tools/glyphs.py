def lettering(cs,assign,text,pixel,y,z,material='ink',prefix='letter'):
 width=sum((len(FONT[ch][0]) if ch!=' ' else 2)+1 for ch in text)-1;x=-width*pixel/2
 for col,ch in enumerate(text):
  if ch==' ':x+=3*pixel;continue
  runs=[]
  for line in FONT[ch]:
   row=[];i=0
   while i<len(line):
    if line[i]=='0':i+=1;continue
    j=i+1
    while j<len(line) and line[j]=='1':j+=1
    row.append((i,j));i=j
   runs.append(row)
  seen=set()
  for row,items in enumerate(runs):
   for i,j in items:
    if (row,i,j) in seen:continue
    k=row+1
    while k<5 and (i,j) in runs[k] and (k,i,j) not in seen:k+=1
    for rr in range(row,k):seen.add((rr,i,j))
    name=f'{prefix}_{col}_{row}_{i}';cs.append({'name':name,'from':[-(x+j*pixel),y+(5-k)*pixel,z-.05],'to':[-(x+i*pixel),y+(5-row)*pixel,z]});assign[name]=(material,['south','east','west','up','down'],False)
  x+=(len(FONT[ch][0])+1)*pixel
